"""The antislop list: every pattern the checker and the hooks read, in one place.

Each pattern carries its own fix and two examples, one it must catch and one it must
let through. tests/test_check.py runs both for every row, and BANNED-FORMULAS.md is
printed from this file by `check.py --list`, so the list, the checker and the docs
cannot disagree.

Severity:
    fail   the text does not ship with it
    flag   reviewed in context: one can be fine, more than THRESHOLD in one text is not

Sources: the writing rules we use at gaja for every post and reply, and the patterns
of blader/humanizer (MIT), itself built on Wikipedia's "Signs of AI writing".
Standard library only.
"""

